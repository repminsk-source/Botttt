def _normalize(s: str) -> str:
    s = s.strip().lower().replace("ё", "е")
    s = s.replace("’", "'").replace("`", "'")
    s = re.sub(r"[.\-]", " ", s)
    s = re.sub(r"\s+", " ", s)
    return s.strip()


# normalized_variant -> canonical_name, строится один раз при импорте модуля.
_LOOKUP: dict[str, str] = {}
for _canonical, _aliases in COUNTRY_ALIASES.items():
    _LOOKUP[_normalize(_canonical)] = _canonical
    for _alias in _aliases:
        _LOOKUP[_normalize(_alias)] = _canonical


def match_country(user_input: str) -> str | None:
    """
    Пытается сопоставить введённое игроком название с реальной страной.
    Возвращает канонiческое название (для сохранения в БД) или None, если
    название не распознано ни как страна, ни как один из её алиасов.
    """
    return _LOOKUP.get(_normalize(user_input))


def is_real_country(user_input: str) -> bool:
    return match_country(user_input) is not None
